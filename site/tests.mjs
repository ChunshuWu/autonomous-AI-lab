export function adapter(path=':memory:',freshStart=false){
  const db=new DatabaseSync(path);
  if(!freshStart){db.exec('CREATE TABLE IF NOT EXISTS settings (name TEXT PRIMARY KEY, value TEXT NOT NULL)');db.prepare('INSERT OR IGNORE INTO settings(name,value) VALUES(?,?)').run('fresh-start-20261005','complete');}
  const prepare=sql=>{let args=[];const q={bind(...values){args=values;return q;},async all(){return {results:db.prepare(sql).all(...args)};},async first(){return db.prepare(sql).get(...args)||null;},async run(){const result=db.prepare(sql).run(...args);return {meta:{changes:result.changes}};}};return q;};
  return {prepare,batch:queries=>Promise.all(queries.map(q=>q.run()))};
}

