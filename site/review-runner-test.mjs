import assert from 'node:assert/strict';
import {Store} from './store.mjs';
import {adapter} from './tests.mjs';
import {seeds} from './fixtures/seeds.mjs';
import {reviewRunnerAction,reviewRunnerContext} from './review-runner.mjs';
import worker from './worker.mjs';
const db=adapter(),store=new Store(db,seeds);await store.init();
const initial=structuredClone(seeds.example);initial.project={id:'runner-check',name:'Runner check',kind:'test'};initial.paused=true;
await db.prepare('INSERT INTO workspaces(name,document,revision) VALUES(?,?,1)').bind('runner-check',JSON.stringify(initial)).run();
const key='runner-check',r=initial.reports[0],a=initial.agents.find(a=>a.id===r.agent_id);
const read=async()=>(await store.read(key)).state;
const ask=(client_id,body='Explain the saved result')=>store.apply(key,{action:'review_question',report_id:r.id,agent_id:a.id,body,client_id,slide_id:'slide-1'},'director');
const q=await ask('first'),q2=await ask('second');
const run=(action,p={},id='runner-one')=>store.apply(key,{action,runner_id:id,...p},'reply_runner');
const protectedState=s=>({agents:s.agents,reports:s.reports,decisions:s.decisions,map:s.research_map,paused:s.paused,direction:s.direction});
const before=protectedState(await read());
await assert.rejects(()=>run('claim',{question_id:q.id,agent_id:a.id}));
await run('heartbeat',{agent_ids:[a.id]});
const claims=await Promise.all([run('claim',{question_id:q.id,agent_id:a.id}),run('claim',{question_id:q.id,agent_id:a.id})]);
assert.equal(claims.filter(Boolean).length,1);const claim=claims.find(Boolean);
assert.equal(await run('claim',{question_id:q2.id,agent_id:a.id}),null);
await assert.rejects(()=>run('renew',{question_id:q.id,lease_id:'wrong'}));
assert.equal(reviewRunnerContext(await read(),{...claim,runner_id:'runner-one'}).agent.id,a.id);
await run('renew',claim);
const body={...claim,body:'Only saved results are available.',client_id:'answer-one',references:[]};
const answer=await run('complete',body);assert.equal((await run('complete',body)).id,answer.id);
assert.equal((await read()).review_questions[0].replies.length,1);
assert.equal((await run('heartbeat',{agent_ids:[a.id]})).pending.length,1);
const c2=await run('claim',{question_id:q2.id,agent_id:a.id});await run('fail',{...c2,error_code:'auth',retryable:false});
assert.equal((await read()).review_questions[1].delivery.status,'failed');
await assert.rejects(()=>store.apply(key,{action:'review_retry',question_id:q2.id},'worker'));
await store.apply(key,{action:'review_retry',question_id:q2.id},'director');
const c3=await run('claim',{question_id:q2.id,agent_id:a.id});assert.ok(c3);
// Expired claims can be recovered; old completions can never overwrite a new turn.
const s=await read();s.review_questions[1].delivery.lease_until=new Date(0).toISOString();
const recovered=reviewRunnerAction(s,{action:'claim',runner_id:'runner-one',question_id:q2.id,agent_id:a.id});assert.ok(recovered);assert.notEqual(recovered.lease_id,c3.lease_id);
assert.throws(()=>reviewRunnerAction(s,{action:'complete',runner_id:'runner-one',...c3,body:'Old',client_id:'stale'}));
s.review_questions[1].delivery.lease_until=new Date(0).toISOString();assert.equal(reviewRunnerAction(s,{action:'claim',runner_id:'runner-one',question_id:q2.id,agent_id:a.id}),null);assert.equal(s.review_questions[1].delivery.status,'failed');
assert.deepEqual(protectedState(await read()),before);
// Dedicated service connection has no research/director actions, requires its own token.
const request=async(payload,token)=>worker.fetch(new Request('https://test.local/api/review-runner',{method:'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:JSON.stringify({workspace:key,runner_id:'runner-one',...payload})}),{DB:db,RUNNER_TOKEN:'local-test'});
assert.equal((await request({action:'heartbeat',agent_ids:[a.id]})).status,403);
assert.equal((await request({action:'heartbeat',agent_ids:[a.id]},'wrong')).status,403);
assert.equal((await request({action:'pause_lab'},'local-test')).status,400);
assert.equal((await request({action:'claim',agent_id:a.id,question_id:q.id},'local-test')).status,200);
assert.equal((await request({action:'heartbeat',agent_ids:[a.id]},'local-test')).status,200);
assert.deepEqual(protectedState(await read()),before);
console.log('PASS: runner authentication, atomic claims, per-agent serialization, lease recovery, stale replies, retry limits, duplicate delivery, and unchanged research.');
