import assert from 'node:assert/strict';
import {Store} from './store.mjs';
import {adapter} from './tests.mjs';
import {assets} from './generated.mjs';
import {seeds} from './fixtures/seeds.mjs';
import {cats} from './identities.mjs';
import worker from './worker.mjs';
const db=adapter(),store=new Store(db,seeds);await store.init();
const ws='discard-study';
await store.apply(ws,{action:'create_project',name:'Discard study'},'director');
const agent=await store.apply(ws,{action:'add_agent',role:'researcher',name:'Researcher',specialty:'Test',question:'Test',plan:['Test']},'director');
const task=(action,fields={},role='task_runner')=>store.apply(ws,{action:'task',task_action:action,runner_id:'fixture',...fields},role);
await task('configure',{client_id:'test-policy',enabled:true,research_enabled:true,max_model_calls:1,scope:'Test'},'director');
await task('submit',{id:'late-task',agent_id:agent.id,kind:'research',summary:'Test',prompt:'Test'},'director');
const packet=await task('claim',{task_id:'late-task'});
const clear={action:'clear_project',archive:false,reason:'The director requested a fresh dashboard without archiving.'};
await assert.rejects(()=>store.apply(ws,clear,'worker'),/director/);
await assert.rejects(()=>store.apply(ws,clear,'director'),/Pause/);
await store.apply(ws,{action:'pause_lab'},'director');
const settings=await db.prepare('SELECT name,value FROM settings ORDER BY name').all();
const library=await store.library(),other=(await store.read('example')).state;
await store.apply(ws,clear,'director');await store.apply(ws,clear,'director');
assert.deepEqual(await db.prepare('SELECT name,value FROM settings ORDER BY name').all(),settings,'No hidden archive or recovery copy');
const cleared=(await store.read(ws)).state;
assert(cleared.paused);assert(cleared.project.cleared_at);assert(!cleared.project.archived_at);
assert.equal(cleared.agents.length,0);assert.equal(cleared.events.length,0);assert(!cleared.tasks);assert(!cleared.workflow);
assert(!(await store.projects({includeArchived:true})).some(p=>p.id===ws));
assert((await store.projects({includeArchived:true,includeCleared:true})).some(p=>p.id===ws));
await assert.rejects(()=>task('complete',{...packet.claim,completion_id:'late-result',result:{outcome:'completed',summary:'Old result',body:'Old result'}}),/cleared/);
await assert.rejects(()=>store.apply(ws,{action:'resume_lab'},'director'),/cleared/);
await new Store(db,seeds).init();assert.deepEqual((await store.read(ws)).state,cleared);
assert.deepEqual(await store.library(),library);assert.deepEqual((await store.read('example')).state,other);
for(const cat of cats)assert(assets[cat.image]);
await store.apply('fresh-three',{action:'create_project',name:'Fresh three'},'director');
const fresh=await store.apply('fresh-three',{action:'add_agent',role:'researcher',name:'Researcher',specialty:'Test',question:'Test',plan:['Test']},'director');
assert.equal(fresh.dashboard_cat_id,agent.dashboard_cat_id);
const response=await worker.fetch(new Request('http://local/api/state?workspace='+ws),{DB:db});
const view=await response.json();assert.notEqual(view.state.project.id,ws);assert(!view.archives.some(p=>p.id===ws));
console.log('Passed no-archive clear, stopped late writes, restart, preserved library/cats, reusable names and old-tab fallback.');
